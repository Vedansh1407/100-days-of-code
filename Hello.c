#include <stdio.h>

int main() {
    int length, breadth, area , perimeter;
    length = 10;
    breadth = 5;
    area = length * breadth;
    perimeter = 2 * (length + breadth);
    printf("Area of rectangle: %d\n", area);
    printf("Perimeter of rectangle: %d\n", perimeter);

    return 0;
}
